//! @page tutorial-beyond Octonions and higher algebras
//!
//! An [octonion](https://en.wikipedia.org/wiki/Octonion) is a number with eight real components, whose product extends the
//! quaternion product and is no longer associative. A [sedenion](https://en.wikipedia.org/wiki/Sedenion) has sixteen
//! components, and its product has [zero divisors](https://en.wikipedia.org/wiki/Sedenion#Zero_divisors). In the @ref math_background "Cayley-Dickson construction", each of them is a
//! pair of values of the previous algebra, and the construction continues without end. **KYOSU**
//! supports every dimension via `kyosu::as_cayley_dickson_n_t<N, T>`, and the octonions via
//! `kyosu::octonion_t<T>`.
//!
//! # Octonions
//!
//! An octonion, `kyosu::octonion_t<T>`, has eight components on the basis \f$1, i, j, k, l, li,
//! lj, lk\f$, and is built from them:
//!
//! @godbolt{doc/tut_beyond_types.cpp}
//!
//! # Higher algebras
//!
//! From dimension 16 the basis elements have no letter. The type is
//! `kyosu::as_cayley_dickson_n_t<N, T>` with `N` the dimension, a component is read and written
//! through `kyosu::get<I>`, and a value prints its components as \f$z_0\f$ to \f$z_{N-1}\f$:
//!
//! @godbolt{doc/tut_beyond_higher.cpp}
//!
//! The functions of the library apply in every dimension.
//!
//! # Associativity
//!
//! From dimension 8, \f$(ab)c\f$ and \f$a(bc)\f$ differ for some triples. On the basis elements
//! \f$i\f$, \f$j\f$, and \f$l\f$, the two products are opposite, \f$(ij)l = -i(jl)\f$.
//!
//! `kyosu::associator` computes the [associator](https://en.wikipedia.org/wiki/Associator)
//! \f$(ab)c - a(bc)\f$. It is zero on the quaternions and below. On the octonions, an
//! [alternative algebra](https://en.wikipedia.org/wiki/Alternative_algebra#The_associator), it
//! is zero when two operands coincide or when the three lie in a quaternion subalgebra:
//!
//! @godbolt{doc/tut_beyond_associativity.cpp}
//!
//! An expression is evaluated as written and never re-associated, so a parenthesis moved in a
//! refactoring changes the result.
//!
